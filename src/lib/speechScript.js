// The speech ("ספיץ") — the phone script agents read step by step.
//
// Stored as PLAIN TEXT in a line format the manager can edit without breaking
// anything, parsed here into steps. The format survives sloppy editing: unknown
// lines just join the sentence, a step with nothing in it disappears.
//
//   # שם השלב            ← starts a new step
//   > מטרת השלב           ← the ONE job this step has to do
//   טקסט רגיל             ← the sentence itself (several lines allowed)
//   - התנגדות | מענה      ← an expected objection and its answer
//   * טיפ                 ← a coaching note shown small under the sentence
//
// The goal line is what makes this a route rather than a list of topics: every
// step earns its place by doing one thing (get permission, make them talk,
// prove you listened, book a time), and an agent who loses the thread mid-call
// can look at the goal instead of re-reading the sentence.
//
// ── Who is speaking, and to whom ─────────────────────────────────────────────
// Hebrew has no neutral "מדבר", so one script cannot fit the whole team: עדי
// says "מדברת", ודיע says "מדבר". The same is true of the person on the other
// end — half the leads in this calendar are women, and "אתה מחפש" is wrong in
// their ear. So the text carries two kinds of token, and the rule is one
// sentence long:
//
//   { }  = ME, the agent      {סוכן}  {מדבר|מדברת}
//   [ ]  = THEM, the lead     [לקוח]  [אתה|את]
//
// Anything in brackets that is neither a known name nor a `male|female` pair is
// left exactly as written — so [X], [Y] and [סניף/זום] survive untouched.
//
// Arabic needs far fewer of these: its first person is genderless, and most
// second-person forms are spelled identically without diacritics. Only the
// forms that genuinely differ ([تعال|تعالي]) are marked.
//
// ── The content ──────────────────────────────────────────────────────────────
// Grounded in how this office actually sells: price is never given on the phone
// (it depends on the מלגה, which is checked in the meeting), the competitor is
// the 980₪ licence course, the differentiator is the mentor and the work
// placement, and the close is a binary time offer.
//
// Arabic is not a nicety here: the leads that come through ודיע are
// overwhelmingly Arabic-speaking — נצרת, אום אל פחם, שפרעם, יפו, ראמה — and
// several arrive already interested in property abroad (ספרד, יוון, דובאי
// appear in the real notes). It is written for those calls, not translated.

export const LANGS = [
  { key: 'he', label: 'עברית', leadFallback: 'שם', leadWord: 'שם הליד' },
  { key: 'ar', label: 'العربية', leadFallback: 'الاسم', leadWord: 'اسم الزبون' },
]

const AGENT_KEYS = ['סוכן', 'agent', 'الوكيل']
const LEAD_KEYS = ['לקוח', 'שם', 'lead', 'الزبون', 'الاسم']

/**
 * Resolve the tokens for one call. Runs BEFORE parsing on purpose: a gender
 * pair like [תגיד|תגידי] contains a pipe, and the objection line format uses
 * the pipe as its separator — resolving first means the only pipe left when the
 * parser runs is a real one.
 */
export function applyVars(text, opts = {}) {
  const {
    agentName = '',
    agentGender = 'm',
    leadName = '',
    leadGender = 'm',
    leadFallback = 'שם',
  } = opts

  const pick = (body, gender) => {
    const [m, f] = body.split('|')
    return ((gender === 'f' ? (f ?? m) : m) || '').trim()
  }

  return String(text || '')
    .replace(/\{([^{}\n]+)\}/g, (whole, body) => {
      if (body.includes('|')) return pick(body, agentGender)
      return AGENT_KEYS.includes(body.trim()) ? agentName || whole : whole
    })
    .replace(/\[([^[\]\n]+)\]/g, (whole, body) => {
      if (body.includes('|')) return pick(body, leadGender)
      return LEAD_KEYS.includes(body.trim()) ? leadName || leadFallback : whole
    })
}

