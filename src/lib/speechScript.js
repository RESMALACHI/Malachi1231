export const DEFAULT_SPEECH = { he: HE, ar: AR }

/**
 * Parse the line format into steps. Forgiving on purpose — the manager edits
 * this by hand, and a typo should cost a line, not the page.
 */
export function parseSpeech(text) {
  const steps = []
  let cur = null

  for (const raw of String(text || '').split(/\r?\n/)) {
    const line = raw.trim()
    if (!line) continue

    if (line.startsWith('#')) {
      cur = {
        stage: line.replace(/^#+\s*/, '').trim() || 'שלב',
        goal: '',
        lines: [],
        objections: [],
        tips: [],
      }
      steps.push(cur)
      continue
    }
    if (!cur) continue // text before the first "#" has no home

    if (line.startsWith('>')) {
      // Last one wins rather than joining — a step has one job, not three.
      cur.goal = line.replace(/^>+\s*/, '').trim() || cur.goal
    } else if (line.startsWith('-')) {
      const body = line.replace(/^-+\s*/, '')
      const cut = body.indexOf('|')
      const q = (cut === -1 ? body : body.slice(0, cut)).trim()
      const a = cut === -1 ? '' : body.slice(cut + 1).trim()
      if (q) cur.objections.push({ q, a })
    } else if (line.startsWith('*')) {
      const tip = line.replace(/^\*+\s*/, '').trim()
      if (tip) cur.tips.push(tip)
    } else {
      cur.lines.push(line)
    }
  }

  return steps
    .filter((s) => s.lines.length || s.objections.length)
    .map((s, i) => ({
      n: i + 1,
      stage: s.stage,
      goal: s.goal,
      text: s.lines.join('\n'),
      objections: s.objections,
      tip: s.tips.join(' · '),
    }))
}
